# Sourced by scripts/gate-g2.sh … gate-g8.sh: the conventions of gate-g1.sh in one place. Exit codes
# are captured, never assumed; the gate's inputs must be committed; a cargo alias, runner or
# wrapper cannot change what the gate runs; a report that cannot be written fails the gate.
# Each gate sets GATE (g2 … g8) and TITLE, calls gate_start, adds rows with row, and ends with
# gate_finish.
set -u
cd "$(dirname "$0")/.."
export RUSTFLAGS="-D warnings" RUSTDOCFLAGS="-D warnings" CARGO_TERM_COLOR=never

gate_start() {
  report=reports/gate-$GATE.md
  work=target/gate-$GATE-run
  rm -rf "$work"
  mkdir -p "$work"
  evidence=""
  rows=""
  fail=0
  head=$(git rev-parse HEAD 2>/dev/null || echo "not a git repository")
  inputs="crates tests tools examples benchmarks scripts runtime Cargo.toml Cargo.lock Makefile rust-toolchain.toml toolchain.lock .cargo"
  # shellcheck disable=SC2086
  dirty=$(git status --porcelain --ignored -- $inputs 2>&1)
  tree=met
  if [ -n "$dirty" ]; then
    tree="not met"
    evidence="$evidence
- The gate's inputs differ from HEAD, so this run would not describe commit $head:
\`\`\`text
$dirty
\`\`\`"
  fi
  dir=$(pwd)
  cfgs="${CARGO_HOME:-$HOME/.cargo}/config ${CARGO_HOME:-$HOME/.cargo}/config.toml"
  while :; do
    cfgs="$cfgs $dir/.cargo/config $dir/.cargo/config.toml"
    [ "$dir" = / ] && break
    dir=$(dirname "$dir")
  done
  for cfg in $cfgs; do
    if [ -f "$cfg" ] && grep -Eq '^[[:space:]]*(\[(alias|build|env|target)|runner[[:space:]]*=|(clippy|fmt|test)[[:space:]]*=)' "$cfg"; then
      tree="not met"
      evidence="$evidence
- \`$cfg\` sets a cargo alias, runner, build or env key, which could change what the gate runs."
    fi
  done
  if env | grep -Eq '^CARGO_(TARGET_[A-Z0-9_]+_RUNNER|BUILD_[A-Z_]+|ALIAS_[A-Z_]+)='; then
    tree="not met"
    evidence="$evidence
- A CARGO_TARGET_*_RUNNER, CARGO_BUILD_* or CARGO_ALIAS_* variable is set, which could change what the gate runs."
  fi
  row "The gate's inputs are committed and no cargo setting changes what it runs" "$tree" "see the commands below"
}

# run <log name> <command...>: run it with its whole output in $work/<name>.log, record the real
# exit code, and on failure the last lines. Returns the command's exit code.
run() {
  name=$1; shift
  "$@" >"$work/$name.log" 2>&1
  code=$?
  if [ "$code" -eq 0 ]; then
    evidence="$evidence
- \`$*\`: exit 0"
  else
    evidence="$evidence
- \`$*\`: exit $code. Last lines:
\`\`\`text
$(tail -n 15 "$work/$name.log")
\`\`\`"
  fi
  return "$code"
}

# row <criterion> <met|not met> <evidence>: one line of the report's table.
row() {
  [ "$2" = met ] || fail=1
  rows="$rows
| $1 | $2 | $3 |"
}

# test_ran <log name> <test name>: the test ran and passed, by libtest's own line.
test_ran() { grep -q "^test $2 \.\.\. ok$" "$work/$1.log"; }

gate_finish() {
  if [ $fail = 0 ]; then verdict="every criterion holds; awaiting the owner's approval"; else verdict="FAILED: at least one criterion is not met"; fi
  if ! cat >"$report" <<EOF
# Gate $(echo "$GATE" | tr g G) · $TITLE

Generated by \`make gate-$GATE\` (scripts/gate-$GATE.sh) for commit \`$head\`. Result: **$verdict**.
A gate passes only when this script exits 0 and the owner approves this report.

| Criterion (ROADMAP.md, docs/16) | Status | Evidence |
| --- | --- | --- |$rows

## Commands run on this host

Host \`$(rustc -vV | sed -n 's/^host: //p')\`, $(rustc --version).
$evidence
EOF
  then
    echo "gate-$GATE: could not write $report" >&2
    exit 1
  fi
  echo "wrote $report: $verdict"
  exit $fail
}
