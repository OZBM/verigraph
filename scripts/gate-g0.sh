#!/bin/sh
# make gate-g0: check the G0 criteria of ROADMAP.md and write reports/gate-g0.md.
# Exits 0 only when every criterion holds. Output has no timestamps, so reruns on the
# same tree and host give the same report.
set -u
cd "$(dirname "$0")/.."
export RUSTFLAGS="-D warnings" RUSTDOCFLAGS="-D warnings" CARGO_TERM_COLOR=never

report=reports/gate-g0.md
log=$(mktemp)
trap 'rm -f "$log"' EXIT
fail=0
evidence=""

# run <label> <command...>: run a command, record its exit code and, on failure, its last lines.
run() {
  label=$1; shift
  if "$@" >"$log" 2>&1; then
    evidence="$evidence
- \`$*\`: exit 0"
    return 0
  fi
  code=$?
  evidence="$evidence
- \`$*\`: exit $code. Last lines:
\`\`\`text
$(tail -n 15 "$log")
\`\`\`"
  return 1
}

# Criterion 1, local half: the workspace builds and passes fmt, clippy and tests on this host.
host=$(rustc -vV | sed -n 's/^host: //p')
c1=met
run fmt cargo fmt --all --check || c1="not met"
run clippy cargo clippy --workspace --all-targets --locked -- -D warnings || c1="not met"
run test cargo test --workspace --locked || c1="not met"
crates=$(ls -d crates/*/ | wc -l | tr -d ' ')
[ "$crates" = 12 ] || c1="not met"

# Criterion 1, remote half, and criterion 2: CI is green on both runners for this commit.
c2="not met"
if ! git rev-parse --git-dir >/dev/null 2>&1; then
  ci="not run: this directory is not a git repository, so there is no commit for CI to build."
elif ! git remote get-url origin >/dev/null 2>&1; then
  ci="not run: the repository has no \`origin\` remote, so CI has never run."
else
  head=$(git rev-parse HEAD)
  runs=$(gh run list --workflow ci.yml --commit "$head" --json conclusion --jq '.[].conclusion' 2>&1)
  if [ "$runs" = success ]; then
    c2=met
    ci="workflow \`ci\` concluded \`success\` for commit $head (jobs linux-x86_64 and macos-arm64)."
  else
    ci="workflow \`ci\` for commit $head: \`${runs:-no run found}\`."
  fi
fi

# Criterion 3: the spec docs are in the repo.
c3=met
missing=""
for f in AGENTS.md ROADMAP.md PROGRESS.md \
  docs/00-vision.md docs/01-architecture.md docs/02-vg-ir-format.md docs/03-vg-sym.md \
  docs/04-types-effects.md docs/05-contracts-verification.md docs/06-codegen-runtime.md \
  docs/07-generation-loop.md docs/08-omnilift.md docs/09-vg-mesh.md docs/10-bootstrap.md \
  docs/11-errata.md docs/12-risks-and-open-questions.md docs/source/original-spec.md \
  docs/research/PROTOCOL.md docs/research/README.md; do
  [ -s "$f" ] || { c3="not met"; missing="$missing $f"; }
done
tracks=$(ls docs/research/R-[0-9][0-9]-*.md 2>/dev/null | grep -cv -- '-report\.md$')
# At least the 13 tracks the kit shipped with; later tracks (R-14 on) add to them.
[ "$tracks" -ge 13 ] || { c3="not met"; missing="$missing (research tracks: $tracks of at least 13)"; }

# P0 deliverables (ROADMAP.md P0.1-P0.6); not gate criteria, listed for the reviewer.
deliverables=""
for p in rust-toolchain.toml toolchain.lock scripts/check-toolchain.sh Makefile .github/workflows/ci.yml \
  tests/corpus/good tests/corpus/bad tests/corpus/alpha benchmarks/kernels benchmarks/synthesis \
  reports docs/adr docs/interface-requests docs/adr/0001-format-encodings.md; do
  if [ -e "$p" ]; then deliverables="$deliverables
- present: \`$p\`"; else deliverables="$deliverables
- MISSING: \`$p\`"; fi
done

toolchain=$(./scripts/check-toolchain.sh 2>&1)

for c in "$c1" "$c2" "$c3"; do [ "$c" = met ] || fail=1; done
if [ $fail = 0 ]; then verdict="every criterion holds; awaiting the owner's approval"; else verdict="FAILED: at least one criterion is not met"; fi

cat >"$report" <<EOF
# Gate G0 · Scaffold

Generated by \`make gate-g0\` (scripts/gate-g0.sh). Result: **$verdict**.
A gate passes only when this script exits 0 and the owner approves this report.

| # | Criterion (ROADMAP.md) | Status | Evidence |
| --- | --- | --- | --- |
| 1 | The workspace builds on macOS ARM64 and Linux x86_64 | local: $c1; CI: $c2 | This host is \`$host\`: $crates crates, fmt, clippy and tests below. Both targets are built only in CI (row 2). |
| 2 | CI is green | $c2 | $ci |
| 3 | The spec docs are in the repo | $c3 | docs 00-12, errata, source spec, research protocol and $tracks research tracks.${missing:+ Missing:$missing} |

## Commands run on this host

Host \`$host\`, $(rustc --version), DEVELOPER_DIR=\`${DEVELOPER_DIR:-unset}\`.
$evidence

## Toolchain on this host (scripts/check-toolchain.sh, informational for G0)

\`\`\`text
$toolchain
\`\`\`

## P0 deliverables
$deliverables
EOF

echo "wrote $report: $verdict"
exit $fail
